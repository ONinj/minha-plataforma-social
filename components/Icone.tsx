export function Avatar({ nome, cor, tamanho = 32 }: { nome: string; cor: string; tamanho?: number }) {
  const iniciais = nome
    .replace(/^@/, "")
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((p) => p[0]?.toUpperCase())
    .join("");
  return (
    <span
      className="avatar"
      style={{
        width: tamanho,
        height: tamanho,
        fontSize: tamanho * 0.38,
        background: `linear-gradient(135deg, ${cor}, color-mix(in srgb, ${cor} 55%, #000))`,
      }}
    >
      {iniciais || "?"}
    </span>
  );
}
